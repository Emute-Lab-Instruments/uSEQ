#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const schemaPath = resolve(root, "protocol/useq-json-v1.json");
const cppPath = resolve(root, "uSEQ/src/firmware/useq_protocol_schema.generated.h");
const tsOutputIndex = process.argv.indexOf("--typescript-output");
const tsPath = tsOutputIndex >= 0
  ? resolve(process.cwd(), process.argv[tsOutputIndex + 1])
  : null;
const schema = JSON.parse(await readFile(schemaPath, "utf8"));

function titleCase(value) {
  return value
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function cppString(value) {
  return JSON.stringify(value);
}

function renderTs() {
  return `// Generated by src-useq/scripts/generate_protocol_schema.mjs. Do not edit.\n` +
    `export const USEQ_JSON_PROTOCOL_SCHEMA = ${JSON.stringify(schema, null, 2)} as const;\n\n` +
    `export type UseqJsonRequestDefinition = typeof USEQ_JSON_PROTOCOL_SCHEMA.requests[number];\n` +
    `export type UseqJsonRequestType = UseqJsonRequestDefinition["type"];\n`;
}

function renderCpp() {
  const fieldArrays = schema.requests.map((request) => {
    if (request.fields.length === 0) return null;
    const rows = request.fields.map((field) =>
      `    {"${field.name}", FieldKind::${titleCase(field.kind)}, ${field.required ? "true" : "false"}},`
    );
    return `inline constexpr FieldDefinition ${request.route}_${request.type.replaceAll("-", "_")}_fields[] = {\n${rows.join("\n")}\n};`;
  }).filter(Boolean);

  const requestRows = schema.requests.map((request) => {
    const fields = request.fields.length === 0
      ? "nullptr"
      : `${request.route}_${request.type.replaceAll("-", "_")}_fields`;
    return `    {"${request.type}", Route::${titleCase(request.route)}, RequestIdPolicy::${titleCase(request.requestId)}, Support::${titleCase(request.hardware)}, Support::${titleCase(request.wasm)}, ${fields}, ${request.fields.length}},`;
  });
  const validFixtureRows = schema.requests.map((request) =>
    `    {${cppString(request.type)}, ${cppString(JSON.stringify(request.example))}, nullptr},`
  );
  const invalidFixtureRows = schema.invalidFixtures.map((fixture) =>
    `    {${cppString(fixture.name)}, ${cppString(JSON.stringify(fixture.payload))}, ${cppString(fixture.error)}},`
  );

  return `// Generated by scripts/generate_protocol_schema.mjs. Do not edit.\n#pragma once\n\n#include <cstddef>\n#include <cstring>\n\nnamespace useq::protocol {\n\ninline constexpr int kWireProtocolVersion = ${schema.wireProtocol};\n\nenum class FieldKind { String, Number, Integer, Boolean, Object, Array, Scalar };\nenum class RequestIdPolicy { Required, Optional };\nenum class Support { Supported, Conditional, Unsupported };\nenum class Route { ${[...new Set(schema.requests.map((request) => titleCase(request.route)))].join(", ")} };\n\nstruct FieldDefinition {\n    const char* name;\n    FieldKind kind;\n    bool required;\n};\n\nstruct RequestDefinition {\n    const char* type;\n    Route route;\n    RequestIdPolicy request_id;\n    Support hardware;\n    Support wasm;\n    const FieldDefinition* fields;\n    size_t field_count;\n};\n\nstruct ConformanceFixture {\n    const char* name;\n    const char* payload;\n    const char* error;\n};\n\n${fieldArrays.join("\n\n")}\n\ninline constexpr RequestDefinition kRequests[] = {\n${requestRows.join("\n")}\n};\n\ninline constexpr ConformanceFixture kValidRequestFixtures[] = {\n${validFixtureRows.join("\n")}\n};\n\ninline constexpr ConformanceFixture kInvalidRequestFixtures[] = {\n${invalidFixtureRows.join("\n")}\n};\n\ninline const RequestDefinition* find_request(const char* type)\n{\n    if (!type) return nullptr;\n    for (const auto& request : kRequests) {\n        if (std::strcmp(request.type, type) == 0) return &request;\n    }\n    return nullptr;\n}\n\n} // namespace useq::protocol\n`;
}

const outputs = [[cppPath, renderCpp()]];
if (tsPath) outputs.push([tsPath, renderTs()]);

if (process.argv.includes("--check")) {
  const mismatches = [];
  for (const [path, expected] of outputs) {
    const actual = await readFile(path, "utf8").catch(() => "");
    if (actual !== expected) mismatches.push(path);
  }
  if (mismatches.length > 0) {
    throw new Error(`Generated protocol files are stale: ${mismatches.join(", ")}`);
  }
} else {
  for (const [path, contents] of outputs) await writeFile(path, contents);
}
